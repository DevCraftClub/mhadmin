declare(strict_types=1);

namespace DevCraft\Enums;

/**
 * Классификация ошибок административной панели для выбора шаблона ответа.
 *
 * @package    DevCraft
 * @since      200.4.0
 * @subpackage Core.Enums
 */
enum AdminErrorKind {

	/**
	 * Ресурс или страница не найдены (HTTP 404).
	 *
	 * @since 200.4.0
	 */
	case NotFound;

	/**
	 * Внутренняя ошибка сервера (HTTP 500).
	 *
	 * @since 200.4.0
	 */
	case ServerError;

	/**
	 * Общая ошибка без специализированного шаблона.
	 *
	 * @since 200.4.0
	 */
	case Generic;

}
